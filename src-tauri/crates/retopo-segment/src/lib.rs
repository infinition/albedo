//! Part and material segmentation for Albedo.
//!
//! Takes a mesh and answers "which bits of this are one thing", at every level
//! of coarseness at once. It does not decide how many parts the model has, and
//! that is on purpose: nothing about a rock sitting on a patch of ground says
//! whether the answer is two parts, or a rock and eleven tufts of grass. The
//! engine produces the whole hierarchy and lets the person looking at the model
//! pick the level, which they can do in a fraction of a second and it cannot.
//!
//! Written for the input that has no other tool: a mesh generated by
//! Hunyuan3D, Meshy or Tripo, which arrives as one shell, one material and one
//! UV atlas, with nothing anywhere in the file admitting it has parts at all.
//!
//! ## Where this sits against the literature
//!
//! The neural work is where the field is — PartField (ICCV 2025), P3-SAM,
//! SAMesh — and all of it wants PyTorch, a GPU and a few hundred megabytes of
//! weights. Albedo is a five megabyte executable that also has to start fast
//! enough to draw an Explorer thumbnail, so none of it can live in here.
//!
//! What is in here instead is the classical stack those papers benchmark
//! against, which is closer than the gap in publication dates suggests: on the
//! Princeton benchmark the Shape Diameter Function scores 0.175 against
//! Normalized Cuts' 0.172 while costing a thirty-fifth as much. Two departures
//! from it, both because of the input:
//!
//! - **Colour is a first class feature.** No classical benchmark uses it,
//!   because benchmark meshes are untextured. On a painted atlas it is the
//!   strongest signal there is, and often the only one.
//! - **The output is a hierarchy, not a partition.** Borrowed from PartField's
//!   final stage, and it is what makes the result something you steer rather
//!   than something you re-run.
//!
//! The neural route stays open from the other end: a per-face label array
//! produced by any of those models drops into the same display, editing and
//! splitting as a result computed here.

